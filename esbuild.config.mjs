import esbuild from "esbuild";
import process from "process";
import { builtinModules } from 'node:module';
import { copyFileSync, existsSync, mkdirSync, readFileSync, watch, writeFileSync } from "fs";
import { dirname, join } from "node:path";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

// Detect entry point: prefer src/main.ts, fallback to main.ts
const hasSrcMain = existsSync("src/main.ts");
const hasRootMain = existsSync("main.ts");

if (hasSrcMain && hasRootMain) {
  console.warn("WARNING: Both src/main.ts and main.ts exist. Using src/main.ts as entry point.");
  console.warn("Consider removing one to avoid confusion.");
}
if (!hasSrcMain && !hasRootMain) {
  console.error("ERROR: Neither src/main.ts nor main.ts found!");
  process.exit(1);
}

// Set entry point based on what exists
const entryPoint = hasSrcMain ? "src/main.ts" : "main.ts";

// Everything Obsidian loads goes to dist/, so a vault links just that folder
const outdir = "dist";
const outfile = `${outdir}/main.js`;
const staticFiles = ["manifest.json"];

// Stylesheet partials live in src/styles/; index.css @imports them in cascade order.
// Inlined verbatim (no CSS rewriting) so the shipped rules equal the partials byte for byte.
const stylesEntry = "src/styles/index.css";

function bundleStyles(entry = stylesEntry) {
	return readFileSync(entry, "utf8").replace(/^@import "(.+?)";\n?/gm, (_, rel) =>
		bundleStyles(join(dirname(entry), rel)),
	);
}

function buildStyles() {
	mkdirSync(outdir, { recursive: true });
	writeFileSync(`${outdir}/styles.css`, bundleStyles());
}

// an editor may replace a partial by delete + write; a read in between fails, the write's own event rebuilds
function rebuildStyles() {
	try {
		buildStyles();
	} catch (e) {
		console.warn(`styles: rebuild skipped (${e instanceof Error ? e.message : String(e)}); retrying on the next change`);
	}
}

function copyStatic(file) {
	if (existsSync(file)) copyFileSync(file, `${outdir}/${file}`);
}

const copyStaticPlugin = {
	name: "copy-static",
	setup(build) {
		build.onEnd(() => {
			mkdirSync(outdir, { recursive: true });
			staticFiles.forEach(copyStatic);
			buildStyles();
		});
	},
};

// Production builds must be reproducible. An inline sourcemap embeds the
// build machine's absolute file paths into main.js, so CI and the Obsidian
// scorecard's reproducer produce byte-different output and the "build
// verification" check fails. Ship production with no sourcemap; keep the
// inline sourcemap only for the dev/watch build for local debugging.
const isProduction =
	process.argv.slice(2).includes("build") ||
	process.argv.slice(2).includes("production");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: [entryPoint],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: isProduction ? false : "inline",
	treeShaking: true,
	outfile: outfile,
	minify: false,
	plugins: [copyStaticPlugin],
});

// Check if this is a one-time build or watch mode
// Check for "build" or "production" argument - supports both patterns
const args = process.argv.slice(2);
const isOneTimeBuild = args.includes("build") || args.includes("production");

if (isOneTimeBuild) {
	// Production build: build once and exit
	await context.rebuild();
	console.log("\n✓ Build complete!");
	console.log(`📦 Release files in ${outdir}/:`);
	console.log("   - main.js");
	console.log("   - styles.css");
	for (const f of staticFiles) {
		if (existsSync(f)) console.log(`   - ${f}`);
	}
	console.log("\n💡 Upload these files to GitHub releases\n");
	await context.dispose();
	process.exit(0);
} else {
	// Development mode: watch for changes
	console.log("\n✓ Development build running in watch mode");
	console.log(`📝 Building to ${outdir}/`);
	console.log("💡 For production builds, run: pnpm build\n");
	await context.watch();
	// esbuild only watches imported files; keep the copies in sync by hand
	for (const f of staticFiles) {
		if (existsSync(f)) watch(f, () => copyStatic(f));
	}
	watch(dirname(stylesEntry), rebuildStyles);
}
